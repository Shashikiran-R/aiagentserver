export class AppError extends Error {
  public code: string;
  public retryable: boolean;
  public details?: any;

  constructor(code: string, message: string, retryable = false, details?: any) {
    super(message);
    this.name = 'AppError';
    this.code = code;
    this.retryable = retryable;
    this.details = details;
  }
}

